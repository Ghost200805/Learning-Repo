#include <iostream>
#include <cmath> // Similar to math module in python
using namespace std;

int main() {
    cout << "Square root of 64 is: " << sqrt(64) << "\n";
    cout << "Round 2.6 to the nearest integer: " << round(2.6) << "\n";
    cout << "The natural logarithm of 2 is: " <<log(2) << "\n";
    cout << "Max of 2 numbers : " << max(10,20) << "\n";
    cout << "Min of 2 numbers : " << min(10,20);
    return 0;
}